#!/usr/bin/env python3
"""Plot raw per-slot road and POI loads as EPS figures.

The input is the CSV generated by ``summarize_slot_loads.py``.  For each
scenario this script writes one road-load figure and one POI-load figure,
each containing all five strategies.
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt


STRATEGY_ORDER = ("ppo", "rise_mpc", "scair", "shortest_distance", "shortest_queue")
STRATEGY_LABELS = {
    "ppo": "PPO",
    "rise_mpc": "RISE-MPC",
    "scair": "SCAIR",
    "shortest_distance": "Shortest distance",
    "shortest_queue": "Shortest queue",
}
COLORS = {
    "ppo": "#1f77b4",
    "rise_mpc": "#d62728",
    "scair": "#2ca02c",
    "shortest_distance": "#9467bd",
    "shortest_queue": "#ff7f0e",
}
LINE_STYLES = {
    "ppo": "-",
    "rise_mpc": "--",
    "scair": "-.",
    "shortest_distance": ":",
    "shortest_queue": (0, (5, 1)),
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Raw per-slot load CSV.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Directory for EPS files (default: a plots_eps directory beside the input CSV).",
    )
    parser.add_argument(
        "--slots",
        type=int,
        default=96,
        help="Number of initial slots to plot (default: 96, slots 0 through 95).",
    )
    return parser.parse_args()


def load_data(path: Path, slot_count: int):
    required = {"scenario", "strategy", "slot", "raw_road_vehicle_min", "raw_poi_person_min"}
    data = defaultdict(lambda: defaultdict(dict))
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames is None or not required.issubset(reader.fieldnames):
            missing = sorted(required - set(reader.fieldnames or ()))
            raise ValueError(f"Missing required CSV columns: {', '.join(missing)}")
        for row in reader:
            slot = int(row["slot"])
            if slot < slot_count:
                data[row["scenario"]][row["strategy"]][slot] = {
                    "road": float(row["raw_road_vehicle_min"]),
                    "poi": float(row["raw_poi_person_min"]),
                }

    if not data:
        raise ValueError(f"No rows found for the first {slot_count} slots in {path}")
    return data


def plot_metric(scenario: str, scenario_data, metric: str, ylabel: str, output: Path, slot_count: int) -> None:
    figure, axis = plt.subplots(figsize=(8.4, 4.8))
    slots = range(slot_count)
    for strategy in STRATEGY_ORDER:
        values = scenario_data.get(strategy, {})
        missing = [slot for slot in slots if slot not in values]
        if missing:
            raise ValueError(f"{scenario}/{strategy} is missing slots: {missing[:5]}")
        axis.plot(
            list(slots),
            [values[slot][metric] for slot in slots],
            label=STRATEGY_LABELS[strategy],
            color=COLORS[strategy],
            linestyle=LINE_STYLES[strategy],
            linewidth=1.7,
        )

    axis.set_title(f"{scenario.replace('_', ' ').title()} - {ylabel} (first {slot_count} slots)")
    axis.set_xlabel("Time slot")
    axis.set_ylabel(ylabel)
    axis.set_xlim(0, slot_count - 1)
    axis.grid(True, color="#d9d9d9", linewidth=0.6, alpha=0.8)
    axis.legend(loc="best", frameon=True, fontsize=9)
    figure.tight_layout()
    figure.savefig(output, format="eps", bbox_inches="tight")
    plt.close(figure)


def main() -> None:
    args = parse_args()
    if args.slots <= 0:
        raise ValueError("--slots must be positive")
    input_path = args.input.resolve()
    output_dir = (args.output_dir or input_path.parent / "plots_eps").resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    data = load_data(input_path, args.slots)

    for scenario in sorted(data):
        scenario_data = data[scenario]
        stem = scenario.lower()
        plot_metric(
            scenario,
            scenario_data,
            "road",
            "Road load (vehicle-min)",
            output_dir / f"{stem}_road_load_first{args.slots}.eps",
            args.slots,
        )
        plot_metric(
            scenario,
            scenario_data,
            "poi",
            "POI load (person-min)",
            output_dir / f"{stem}_poi_load_first{args.slots}.eps",
            args.slots,
        )

    print(f"Wrote {2 * len(data)} EPS figures to {output_dir}")


if __name__ == "__main__":
    main()
